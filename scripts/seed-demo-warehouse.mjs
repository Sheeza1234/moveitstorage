/**
 * Builds a complete multi-floor warehouse THROUGH THE BACKEND API (the same calls the portal makes), so the
 * data is stored in the database like anything entered by hand. It does not touch existing warehouses.
 *
 *   npm run seed:demo-warehouse            (app must be running)
 *   BASE_URL=http://localhost:3001 npm run seed:demo-warehouse
 *
 * Shape (matches the verification case): F1 3 zones / 4 rows x 8 racks / 4 levels x 4 positions,
 * F2 2 zones / 3 rows x 6 racks, F3 2 zones / 2 rows x 5 racks x 3 levels. ~5% of positions are blocked.
 */
const BASE = process.env.BASE_URL || "http://localhost:3000";

const EMAIL = process.env.SEED_EMAIL || "admin@moveit.local";
const PASSWORD = process.env.SEED_PASSWORD || "Admin@12345";
const COMMON = { "content-type": "application/json", "x-moveit-rpc": "1" };
let cookie = "";

function unreachable() {
  console.error(`\nCannot reach the app at ${BASE}.\nStart it first in another terminal (npm run dev) and wait for "Ready", then run this again.\nIf it runs on a different port: BASE_URL=http://localhost:3001 npm run seed:demo-warehouse\n`);
  process.exit(1);
}

// sign in once (as a Super Admin) and reuse the session cookie
async function signIn() {
  const res = await fetch(`${BASE}/api/auth/login`, { method: "POST", headers: COMMON, body: JSON.stringify({ email: EMAIL, password: PASSWORD }) }).catch(unreachable);
  if (!res.ok) {
    console.error(`\nSign-in failed for ${EMAIL} (${res.status}). Set SEED_EMAIL / SEED_PASSWORD to a Super Admin account.\n`);
    process.exit(1);
  }
  cookie = (res.headers.getSetCookie?.() ?? []).map((c) => c.split(";")[0]).join("; ");
}

async function rpc(service, method, ...args) {
  if (!cookie) await signIn();
  const res = await fetch(`${BASE}/api/rpc/${service}/${method}`, {
    method: "POST",
    headers: { ...COMMON, cookie },
    body: JSON.stringify({ args }),
  }).catch(unreachable);
  // the API tags `undefined` values; decode them like the browser client does
  const body = JSON.parse(await res.text(), (_k, v) => (v && typeof v === "object" && v.$moveit === "undefined" ? undefined : v));
  if (!body.ok) throw new Error(`${service}.${method}: ${body.error?.message}`);
  return body.result;
}

const existing = (await rpc("warehouseService", "getWarehouses")).find((w) => w.code === "DEMO-01");
if (existing) {
  console.log(`DEMO-01 already exists (${existing.id}). Nothing to do.`);
  process.exit(0);
}

let wh = await rpc("warehouseService", "createWarehouse", {
  name: "Demo Hub (generated through the API)",
  code: "DEMO-01",
  address: "Plot 1, Demo Industrial Area",
  city: "Dubai",
  country: "UAE",
  description: "Generated by scripts/seed-demo-warehouse.mjs to exercise the 3D layout.",
  capacityUnit: "SQ_FT",
  totalCapacitySqFt: 240000,
  status: "ACTIVE",
});

const plan = [
  { floor: "Floor 1", code: "F1", zones: [{ name: "Zone A", rows: ["A", "B"], racks: 8, levels: 4, ppl: 4 }, { name: "Zone B", open: true, bays: 6 }, { name: "Zone C", rows: ["A", "B"], racks: 8, levels: 4, ppl: 4 }] },
  { floor: "Floor 2", code: "F2", zones: [{ name: "Zone 2A", rows: ["A", "B"], racks: 6, levels: 4, ppl: 4 }, { name: "Zone 2B", rows: ["A"], racks: 6, levels: 4, ppl: 4 }] },
  { floor: "Floor 3", code: "F3", zones: [{ name: "Zone 3A", rows: ["A"], racks: 5, levels: 3, ppl: 4 }, { name: "Zone 3B", rows: ["A"], racks: 5, levels: 3, ppl: 4 }] },
];

const pad = (n) => String(n).padStart(2, "0");
let n = 0;
for (const f of plan) {
  // the warehouse already has its Ground Floor: use it as Floor 1, add the others
  if (f.code === "F1") wh = await rpc("warehouseService", "updateFloor", wh.floors[0].id, { name: f.floor, code: `${wh.code}-${f.code}` });
  else wh = await rpc("warehouseService", "createFloor", wh.id, { name: f.floor, code: `${wh.code}-${f.code}` });
  const floor = wh.floors.find((x) => x.code === `${wh.code}-${f.code}`);
  for (const z of f.zones) {
    const zc = `${f.code}-${z.name.replace(/\W/g, "").toUpperCase()}`;
    wh = await rpc("warehouseService", "createZone", wh.id, { floorId: floor.id, name: z.name, code: zc, isOpenFloor: Boolean(z.open) });
    const zone = wh.floors.find((x) => x.id === floor.id).zones.find((x) => x.code === zc);
    if (z.open) {
      for (let b = 1; b <= z.bays; b++) wh = await rpc("warehouseService", "createSlot", zone.id, { name: `Open Storage Bay ${pad(b)}`, code: `${zc}-BAY${pad(b)}`, capacitySqFt: 1000, storageType: "FLOOR" });
      continue;
    }
    for (const row of z.rows) {
      for (let r = 1; r <= z.racks; r++) {
        wh = await rpc("warehouseService", "createRack", zone.id, {
          name: `Rack ${row}-${pad(r)}`,
          code: `${zc}-${row}${pad(r)}`,
          rowLabel: row,
          levels: z.levels,
          positionsPerLevel: z.ppl,
          positionCapacitySqFt: 250,
        });
        n++;
      }
    }
  }
}

// block ~5% of positions deterministically so statuses are not all the same
const slots = wh.floors.flatMap((f) => f.zones.flatMap((z) => [...(z.racks ?? []).flatMap((r) => r.slots), ...(z.directSlots ?? [])]));
let blocked = 0;
for (const [i, s] of slots.entries()) {
  if (i % 20 === 7) {
    wh = await rpc("warehouseService", "updateSlot", s.id, { blocked: true });
    blocked++;
  }
}
// ---- business data through the real flow: allocation (reserves) -> items received (occupies) ----
let customers = await rpc("customerService", "getCustomers");
const wanted = [
  ["Al Noor Trading LLC", "noor"],
  ["Gulf Interiors FZE", "gulf"],
  ["Desert Rose Logistics", "rose"],
  ["Skyline Furniture Co", "skyline"],
];
for (const [name, key] of wanted) {
  const email = `demo.${key}@example.com`;
  if (!customers.some((c) => c.email === email)) {
    await rpc("customerService", "createCustomer", { type: "CORPORATE", companyName: name, email, phone: "+971500000000", address: "Dubai", city: "Dubai", country: "UAE", status: "ACTIVE" });
  }
}
customers = (await rpc("customerService", "getCustomers")).filter((c) => /^demo\.\w+@example\.com$/.test(c.email));

const today = new Date().toISOString().slice(0, 10);
const end = new Date(Date.now() + 180 * 864e5).toISOString().slice(0, 10);
// re-read: statuses changed when positions were blocked above
wh = await rpc("warehouseService", "getWarehouseById", wh.id);
const current = wh.floors.flatMap((f) => f.zones.flatMap((z) => [...(z.racks ?? []).flatMap((r) => r.slots), ...(z.directSlots ?? [])]));
const open = current.filter((s) => s.status !== "BLOCKED" && s.storageType !== "FLOOR");
// pattern per 10 positions: 1 reserved (blue), 3 + 4 occupied (red), 6 partially occupied (orange), 8 reserved part-space
const kinds = { 1: "reserved", 3: "occupied", 4: "occupied", 6: "partial", 8: "reserved-part" };
const done = { reserved: 0, occupied: 0, partial: 0 };
for (const [i, slot] of open.entries()) {
  const kind = kinds[i % 10];
  if (!kind) continue;
  const customer = customers[i % customers.length];
  const need = kind === "reserved-part" ? 150 : 250;
  let alloc = await rpc("allocationService", "createAllocationRequirement", {
    customerId: customer.id, storageType: "SLOT", requiredCapacity: need, capacityUnit: "SQ_FT",
    startDate: today, expectedEndDate: end, preferredWarehouseId: wh.id, notes: "Seeded by seed-demo-warehouse",
  });
  alloc = await rpc("allocationService", "confirmAllocation", alloc.id, slot.id);
  if (kind === "occupied" || kind === "partial") {
    const footprint = kind === "occupied" ? 250 : 100;
    await rpc("inventoryService", "recordItemsIn", {
      customerId: customer.id, allocationId: alloc.id, warehouseId: wh.id, locationId: slot.id,
      packageType: "PALLET", itemCount: footprint === 250 ? 12 : 5, capacityFootprintSqFt: footprint, capacityUnit: "SQ_FT",
      description: `Stored goods for ${customer.name}`,
    });
    done[kind]++;
  } else done.reserved++;
}
wh = (await rpc("warehouseService", "getWarehouseById", wh.id));
console.log(`Business data: ${done.reserved} reserved, ${done.occupied} occupied, ${done.partial} partially occupied positions across ${customers.length} customers.`);
console.log(`Created ${wh.code} (${wh.id}): ${wh.floors.length} floors, ${n} racks, ${slots.length} positions (${blocked} blocked).`);
console.log(`Open ${BASE}/warehouses/${wh.id}`);
